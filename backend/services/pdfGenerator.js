function renderLandlordStatement(doc, data) {
  doc.fontSize(14).font('Helvetica-Bold').fillColor('#0f172a').text('MONTHLY LANDLORD REMITTANCE STATEMENT', { align: 'center' });
  doc.moveDown(1.5);

  doc.fontSize(10).font('Helvetica').fillColor('#334155');
  doc.text(`STATEMENT PERIOD: ${data.billing_month || new Date().toISOString().slice(0, 7)}`);
  doc.text(`LANDLORD: ${data.landlord_name || 'Landlord'} (${data.landlord_id || 'N/A'})`);
  doc.text(`PROPERTY: ${data.property_name || 'All Assigned Properties'}`);
  doc.moveDown(1);

  doc.font('Helvetica-Bold').text('FINANCIAL SUMMARY (DUAL CURRENCY KES / USD):');
  doc.moveDown(0.5);

  const rate = data.usd_exchange_rate || 129.50;
  const grossKes = data.gross_collected_kes || 0;
  const mgmtFeeKes = data.management_fee_kes || 0;
  const netPayableKes = data.net_payable_kes || (grossKes - mgmtFeeKes);

  doc.font('Helvetica').text(`Gross Rent Collected: KES ${grossKes.toLocaleString('en-KE')}  ($${(grossKes / rate).toFixed(2)} USD)`);
  doc.text(`Less Management Commission (${data.commission_percent || 10}%): KES ${mgmtFeeKes.toLocaleString('en-KE')}  ($${(mgmtFeeKes / rate).toFixed(2)} USD)`);
  doc.font('Helvetica-Bold').fillColor('#10b981').text(`NET REMITTANCE PAYABLE: KES ${netPayableKes.toLocaleString('en-KE')}  ($${(netPayableKes / rate).toFixed(2)} USD)`);
  doc.fillColor('#334155').font('Helvetica').text(`Applied Live CBK Exchange Rate: 1 USD = ${rate} KES`);
}

