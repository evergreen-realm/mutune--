const PDFDocument = require('pdfkit');
const logger = require('../utils/logger');
const { calculateStampDuty } = require('./financials');

/**
 * PDF Document Generator for MutuneRent Pro Official Paperwork
 */
function generateLegalPDF(docType, data) {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ margin: 50, size: 'A4' });
      const buffers = [];

      doc.on('data', buffers.push.bind(buffers));
      doc.on('end', () => {
        const pdfBuffer = Buffer.concat(buffers);
        resolve(pdfBuffer);
      });

      // Header Banner Styling
      doc.rect(0, 0, doc.page.width, 90).fill('#0f172a');
      doc.fillColor('#10b981').fontSize(22).font('Helvetica-Bold').text('MUTUNERENT PRO', 50, 25);
      doc.fillColor('#94a3b8').fontSize(9).font('Helvetica').text('Enterprise Property Accounting & Legal Paperwork Suite', 50, 52);
      doc.fillColor('#ffffff').fontSize(10).font('Helvetica-Bold').text(getDocTitle(docType).toUpperCase(), doc.page.width - 250, 35, { align: 'right', width: 200 });

      doc.moveDown(4);
      doc.fillColor('#1e293b');

      switch (docType) {
        case 'lease_agreement':
          renderLeaseAgreement(doc, data);
          break;
        case 'demand_note_7day':
          renderDemandNote(doc, data);
          break;
        case 'quit_notice_30day':
          renderQuitNotice(doc, data);
          break;
        case 'landlord_remittance_statement':
          renderLandlordStatement(doc, data);
          break;
        case 'agent_salary_voucher':
          renderAgentSalaryVoucher(doc, data);
          break;
        case 'etims_tax_receipt':
          renderETIMSReceipt(doc, data);
          break;
        case 'rrt_landlord_complaint':
          renderRRTComplaintForm(doc, data);
          break;
        case 'rrt_tenant_response':
          renderRRTResponseForm(doc, data);
          break;
        default:
          renderGenericDocument(doc, data);
      }

      // Footer
      const bottom = doc.page.height - 50;
      doc.fontSize(8).fillColor('#64748b').text('Generated by MutuneRent Pro Legal Engine • KRA eTIMS & Cap 301 Compliant • Page 1 of 1', 50, bottom, { align: 'center', width: doc.page.width - 100 });

      doc.end();
    } catch (err) {
      logger.error('PDF Generation Error', { docType, error: err.message });
      reject(err);
    }
  });
}

function getDocTitle(docType) {
  const titles = {
    lease_agreement: 'Tenancy Lease Agreement',
    demand_note_7day: '7-Day Rent Demand Note',
    quit_notice_30day: '30-Day Notice to Quit & Vacate',
    landlord_remittance_statement: 'Landlord Remittance Statement',
    agent_salary_voucher: 'Agent Salary & Commission Voucher',
    etims_tax_receipt: 'KRA eTIMS Tax Invoice Receipt',
    rrt_landlord_complaint: 'Rent Restriction Tribunal Complaint Form',
    rrt_tenant_response: 'Rent Restriction Tribunal Response Form'
  };
  return titles[docType] || 'Official Document';
}

function renderLeaseAgreement(doc, data) {
  doc.fontSize(13).font('Helvetica-Bold').fillColor('#0f172a').text('RESIDENTIAL / COMMERCIAL TENANCY LEASE AGREEMENT', { align: 'center' });
  doc.moveDown(1);

  doc.fontSize(9.5).font('Helvetica').fillColor('#334155');
  doc.text(`THIS LEASE AGREEMENT is made this ${data.signing_date || new Date().toLocaleDateString('en-KE')} between:`);
  doc.moveDown(0.5);

  doc.font('Helvetica-Bold').text(`LANDLORD / LESSOR: ${data.landlord_name || 'Property Owner'}`);
  doc.font('Helvetica').text(`Email: ${data.landlord_email || 'N/A'} • Phone: ${data.landlord_phone || 'N/A'}`);
  doc.moveDown(0.5);

  doc.font('Helvetica-Bold').text(`TENANT / LESSEE: ${data.tenant_name || 'Tenant Name'}`);
  doc.font('Helvetica').text(`Tenant Code: ${data.tenant_code || 'N/A'} • ID/Passport: ${data.id_number || 'N/A'} • Phone: ${data.tenant_phone || 'N/A'}`);
  doc.moveDown(0.8);

  doc.font('Helvetica-Bold').text('1. PREMISES & FINANCIAL TERMS:');
  doc.font('Helvetica').text(`Property: ${data.property_name || 'Property Name'} (Unit: ${data.unit_number || 'N/A'})`);
  doc.text(`Monthly Rent: KES ${(data.rent_amount_kes || 0).toLocaleString('en-KE')} payable by the 5th of each month.`);
  doc.text(`Refundable Security Deposit: KES ${(data.deposit_amount_kes || 0).toLocaleString('en-KE')}.`);
  doc.text(`Lease Term: ${data.lease_duration_months || 12} Months commencing ${data.start_date || new Date().toLocaleDateString('en-KE')}.`);
  doc.moveDown(0.8);

  // Step 4.2: Stamp Duty Advisory Box (Section 19, Stamp Duty Act Cap 480)
  const stampDuty = calculateStampDuty({
    monthlyRentKes: data.rent_amount_kes || 0,
    leaseDurationMonths: data.lease_duration_months || 12
  });

  doc.rect(50, doc.y, doc.page.width - 100, 48).fillAndStroke('#f8fafc', '#cbd5e1');
  const stampY = doc.y + 6;
  doc.fillColor('#0369a1').fontSize(8.5).font('Helvetica-Bold').text('STAMP DUTY ADVISORY (KENYA STAMP DUTY ACT CAP 480):', 60, stampY);
  doc.fillColor('#334155').fontSize(8).font('Helvetica').text(`Annual Rental Value: KES ${stampDuty.annual_rent_kes.toLocaleString('en-KE')} | Stamp Duty Payable: KES ${stampDuty.stamp_duty_payable_kes.toLocaleString('en-KE')}`, 60, stampY + 12);
  doc.fillColor('#64748b').text(`Assessment Rate: ${stampDuty.rate_description} • Informational e-Slip Notice`, 60, stampY + 24);
  doc.y = stampY + 45;
  doc.moveDown(0.8);

  // Step 4.1: Signatures & Digital Attestation Block
  doc.fontSize(9.5).fillColor('#0f172a').font('Helvetica-Bold').text('2. SIGNATURES & ATTESTATION:');
  doc.moveDown(0.5);

  if (data.is_digitally_signed || data.signature_hash) {
    // Digital E-Signature Attestation Block
    doc.rect(50, doc.y, doc.page.width - 100, 68).fillAndStroke('#f0fdf4', '#86efac');
    const badgeY = doc.y + 6;
    doc.fillColor('#15803d').fontSize(9).font('Helvetica-Bold').text('✓ DIGITALLY SIGNED & VERIFIED VIA 2-STEP SMS OTP', 60, badgeY);
    doc.fillColor('#166534').fontSize(8).font('Helvetica').text(`Signed By: ${data.tenant_name} (${data.tenant_phone || 'Verified Handset'})`, 60, badgeY + 14);
    doc.text(`Timestamp (EAT): ${data.signed_at || new Date().toISOString()}`, 60, badgeY + 26);
    doc.text(`Verification Hash (SHA-256): ${data.signature_hash || 'SHA256-MUTUNE-SECURE-LEAD-9988'}`, 60, badgeY + 38);
    doc.fillColor('#15803d').font('Helvetica-Bold').text(`Legal Status: Enforceable Electronic Signature (Kenya Information & Communications Act)`, 60, badgeY + 50);
    doc.y = badgeY + 68;
  } else {
    doc.moveDown(1.5);
    doc.fontSize(9).font('Helvetica').fillColor('#475569');
    doc.text('_____________________________                  _____________________________');
    doc.text('Landlord / Authorized Agent Signature          Tenant Signature');
  }
}

